
from ust.python.util import utils
from ust.python.util.dataset import Dataset
from ust.python.util.logger_factory import logger

ust_or_release = ''             # Valid values are 'ust' or 'release'
control_id = 0                     # Enter an integer that is the ust_control_id or release_control_id
organization_id = ''            # Optional; only used if control_id is not passed. If control_id == 0 or None, the script will retrieve the most recent control_id for the organization. 

# Set standalone_export to True to export the summaries genereated by this script to a standalone file. The default use of this
# script is to create additional worksheets to be included in the QAQC summary generated by qa_check.py; this occurs when
# standalone_export = False. 
standalone_export = False         
# These variables will be ignored if standalone_export = False. If True, they can usually be left unset. If standalone_export = True, 
# and the variables below are not set, this script will generate an Excel spreadsheet in the appropriate state folder in the repo 
# under /ust/python/exports/QAQC. This file directory and its contents are excluded from pushes to the repo by .gitignore.
export_file_path = None
export_file_dir = None
export_file_name = None


